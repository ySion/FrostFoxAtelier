import { Resvg } from '@resvg/resvg-js';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../', import.meta.url));
const manifest = JSON.parse(readFileSync(root + 'assets/icons/manifest.json', 'utf8'));
const size = manifest.pixels;
const stroke = manifest.stroke ?? 2;
if (!(stroke > 0 && stroke <= 3)) throw new Error('manifest.stroke must be in (0, 3]');
if (!Number.isInteger(size) || size < 1 || size > 256)
  throw new Error('manifest.pixels must be an integer in 1..256');
let generated = '// Generated by tools/icons/generate.mjs. Do not edit.\n' +
  `constexpr unsigned icon_source_size=${size};\n`;
const emitPng = process.argv.includes('--png');
if (emitPng) mkdirSync(root + 'out/icons-preview', { recursive: true });
for (const [name, source] of Object.entries(manifest.icons)) {
  // Tabler's 2 px outline reads heavier than Houdini's shaded icons at UI sizes.
  const svg = readFileSync(root + `assets/icons/svg/${source}.svg`, 'utf8')
    .replace('stroke-width="2"', `stroke-width="${stroke}"`);
  const rendered = new Resvg(svg, { fitTo: { mode: 'width', value: size } }).render();
  if (rendered.width !== size || rendered.height !== size) throw new Error(`Invalid size: ${name}`);
  if (emitPng) writeFileSync(root + `out/icons-preview/${name}.png`, rendered.asPng());
  const rgba = rendered.pixels;
  const runs = [];
  let previous = rgba[3], count = 0;
  for (let i = 3; i < rgba.length; i += 4) {
    if (rgba[i] !== previous || count === 65535) {
      runs.push(`{${count},${previous}}`); count = 0; previous = rgba[i];
    }
    ++count;
  }
  runs.push(`{${count},${previous}}`);
  generated += `constexpr Run ${name}_runs[]{\n`;
  for (let i = 0; i < runs.length; i += 12) generated += '    ' + runs.slice(i, i + 12).join(',') + ',\n';
  generated += '};\n';
}
writeFileSync(root + 'modules/gui/ui/src/detail/icon_data.inl', generated);
